"""Live Brevo integration test.

This test ACTUALLY HITS THE BREVO HTTP API and sends a real email
to uddipan@gmail.com. It is OFF by default — gated by the
RUN_LIVE_BREVO=1 environment variable.

Why opt-in (not always-on):
  - Hits an external API (network dependency in CI)
  - Counts against the Brevo monthly send quota
  - Spams uddipan@gmail.com if accidentally run in a loop
  - Requires `secrets/brevo.yaml` to be present + readable

When to run:
  - After Step 10 lands, as a one-off verification that the
    secrets-load + Brevo HTTP plumbing still works end-to-end
  - After any change to send_email or brevo_secrets
  - After rotating the Brevo API key

How to run:
    RUN_LIVE_BREVO=1 pytest \\
        tests/notifications/test_send_email_live.py -v -s

The `-s` flag is important — it surfaces the print() output that
shows the message_id Brevo returns. Save that ID; if delivery
fails downstream (e.g. Gmail Promotions tab), Brevo's transactional
log can be queried by message_id.

Notes:
  - The default destination is uddipan@gmail.com (the operator's
    subscriber #1 in production). Override via
    LIVE_BREVO_TO=other@example.com if you want to send elsewhere.
  - The test sends ONE plain-shaped EmailBody (subject + minimal
    HTML/plain). It is NOT verifying body rendering — that's
    compose_email's responsibility, covered in
    test_compose_email.py.
  - Success = the API returns 2xx and a message_id. This does NOT
    guarantee the email lands in the inbox (greylisting, spam,
    Gmail Promotions tab, etc.). Check the inbox manually after
    the test passes.
"""
from __future__ import annotations

import os
from datetime import UTC, datetime
from pathlib import Path

import pytest

from trip_ema.config.brevo_secrets import load_brevo_api_key
from trip_ema.notifications.compose_email import EmailBody
from trip_ema.notifications.send_email import send_email
from trip_ema.persistence.subscribers_repo import SubscriberRecord


_LIVE_BREVO_ENABLED = os.environ.get("RUN_LIVE_BREVO") == "1"
_SECRETS_FILE = Path("secrets/brevo.yaml")
_DEFAULT_TO = os.environ.get("LIVE_BREVO_TO", "uddipan@gmail.com")
_DEFAULT_FROM = "weeklystocksignals@outlook.com"


live_brevo = pytest.mark.skipif(
    not _LIVE_BREVO_ENABLED,
    reason=(
        "Live Brevo test is opt-in. Set RUN_LIVE_BREVO=1 to enable. "
        "Sends a real email to uddipan@gmail.com via the Brevo HTTP "
        "API."
    ),
)


@live_brevo
def test_brevo_secrets_load():
    """Step 1: the secrets file exists, is permission-locked, and
    parses into a non-empty API key with the xkeysib- prefix.

    Runs first (alphabetical) so a misconfigured file fails fast
    before we attempt a send.
    """
    if not _SECRETS_FILE.exists():
        pytest.skip(
            f"{_SECRETS_FILE} not present — cannot exercise live Brevo. "
            f"Place a brevo.yaml with `api_key: xkeysib-...` at that "
            f"path (chmod 600), then re-run."
        )

    api_key = load_brevo_api_key(_SECRETS_FILE)
    assert api_key, "load_brevo_api_key returned empty string"
    assert api_key.startswith("xkeysib-"), (
        f"Loaded API key does not have the expected Brevo prefix. "
        f"Got prefix: {api_key[:10]!r}"
    )


@live_brevo
def test_send_test_email_to_uddipan():
    """Step 2: load the API key, build a minimal EmailBody, send to
    uddipan@gmail.com. Asserts the API returns success (2xx with a
    message_id).
    """
    if not _SECRETS_FILE.exists():
        pytest.skip(
            f"{_SECRETS_FILE} not present — cannot exercise live Brevo."
        )

    api_key = load_brevo_api_key(_SECRETS_FILE)

    subscriber = SubscriberRecord(
        subscriber_id=1,
        transport="email",
        address=_DEFAULT_TO,
        notify_cadence_minutes=60,
        last_notified_at=None,
        is_active=True,
    )

    now = datetime.now(UTC)
    stamp = now.strftime("%Y-%m-%d %H:%M:%S UTC")
    body = EmailBody(
        subject=f"[trip_ema] Live Brevo verification ({stamp})",
        html=(
            "<html><body style='font-family:sans-serif'>"
            "<h2>WeeklyStockSignals — live Brevo check</h2>"
            f"<p>This is a test message sent at <b>{stamp}</b> "
            "to verify that the Brevo HTTP API integration is "
            "operational end-to-end.</p>"
            "<p>No signals are reported. Nothing to act on.</p>"
            "<hr>"
            "<p style='color:#888;font-size:12px'>"
            "Generated by tests/notifications/test_send_email_live.py "
            "with RUN_LIVE_BREVO=1.</p>"
            "</body></html>"
        ),
        plain_text=(
            f"WeeklyStockSignals — live Brevo check\n"
            f"\n"
            f"This is a test message sent at {stamp} to verify "
            f"that the Brevo HTTP API integration is operational "
            f"end-to-end.\n"
            f"\n"
            f"No signals are reported. Nothing to act on.\n"
            f"\n"
            f"--\n"
            f"Generated by tests/notifications/test_send_email_live.py "
            f"with RUN_LIVE_BREVO=1.\n"
        ),
        signal_count=0,
    )

    result = send_email(
        subscriber, body,
        api_key=api_key,
        from_address=_DEFAULT_FROM,
        from_name="WeeklyStockSignals",
        now=now,
    )

    # Print result regardless so the user sees the message_id (or
    # the failure reason) when running with pytest -s.
    print()
    print(f"  live Brevo result:")
    print(f"    subscriber_id  : {result.subscriber_id}")
    print(f"    address        : {result.address}")
    print(f"    success        : {result.success}")
    print(f"    error          : {result.error}")
    print(f"    sent_at        : {result.sent_at.isoformat()}")

    assert result.success, (
        f"Live Brevo send failed: {result.error}. "
        f"Check (a) secrets/brevo.yaml has a valid key, "
        f"(b) network egress to api.brevo.com is open, "
        f"(c) the from_address {_DEFAULT_FROM} is still a verified "
        f"sender in the Brevo console."
    )
